if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(
        description="Skill canonicalisation utilities for EdgeDash."
    )
    parser.add_argument(
        "--audit",
        action="store_true",
        help="Print skill frequency report from the database (read-only).",
    )
    parser.add_argument(
        "--suggest-aliases",
        action="store_true",
        dest="suggest_aliases",
        help=(
            "Ask the model to suggest alias groupings for unaliased skills. "
            "ONE model call. Prints YAML only — writes nothing."
        ),
    )
    parser.add_argument(
        "--db",
        default="edgedash.db",
        metavar="PATH",
        help="Path to the SQLite database (default: edgedash.db).",
    )
    parser.add_argument(
        "--config",
        default="config.yaml",
        metavar="PATH",
        help="Path to config.yaml (default: config.yaml).",
    )

    args = parser.parse_args()

    if args.audit:
        _run_audit(db_path=args.db, config_path=args.config)
    elif args.suggest_aliases:
        _run_suggest_aliases(db_path=args.db, config_path=args.config)
    else:
        parser.print_help()
